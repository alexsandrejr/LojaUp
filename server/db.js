const RLS_SQL = [...TABLES, 'backup_staging', 'app_secrets', 'login_attempts', 'schema_version'].map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n');

// ---------- Drivers ----------

const identity = (v) => v;

// Postgres de verdade (Supabase), via pg
function pgDriver(url) {
  const pg = require('pg');
  pg.types.setTypeParser(20, Number); // bigint (COUNT, SUM de inteiros)
  pg.types.setTypeParser(1700, parseFloat); // numeric (AVG, ROUND)
  pg.types.setTypeParser(1082, identity); // date: mantém o texto 'AAAA-MM-DD'
  pg.types.setTypeParser(1114, identity); // timestamp
  pg.types.setTypeParser(1184, identity); // timestamptz
  const local = /@(localhost|127\.0\.0\.1)[:/]/.test(url);
  const pool = new pg.Pool({
    connectionString: url.replace(/[?&]sslmode=[^&]*/, ''),
    // O certificado do Supabase não é de uma autoridade conhecida pelo Node: a conexão é criptografada,
    // mas o certificado não é verificado.
    ssl: local ? false : { rejectUnauthorized: false },
    max: 3,
    idleTimeoutMillis: 10000,
  });
  return {
    async session(fn) {
      const client = await pool.connect();
      try {
        return await fn((sql, params) => client.query(sql, params));
      } finally {
        client.release();
      }
    },
    query: (sql, params) => pool.query(sql, params),
    close: () => pool.end(),
  };
}

// Postgres embutido (PGlite), para desenvolvimento e testes. dataDir = null cria um banco só na memória.
function pgliteDriver(dataDir) {
  // Nome numa variável para a Vercel não empacotar o PGlite, que só serve em desenvolvimento
  const pglite = '@electric-sql/pglite';
  const { PGlite } = require(pglite);
  const db = new PGlite({
    dataDir: dataDir || undefined,
    parsers: { 1700: parseFloat, 1082: identity, 1114: identity, 1184: identity },
  });
  // O PGlite tem uma conexão só: as sessões entram numa fila
  let queue = Promise.resolve();
  const run = (sql, params) => (params && params.length ? db.query(sql, params) : db.query(sql))
    .then((r) => ({ rows: r.rows, rowCount: r.affectedRows ?? r.rows.length }));
  const multi = (sql) => db.exec(sql).then((rs) => ({ rows: rs.at(-1)?.rows || [], rowCount: 0 }));
  const exec = (sql, params) => (params && params.length ? run(sql, params) : (sql.includes(';') ? multi(sql) : run(sql)));
  return {
    session(fn) {
      const next = queue.then(() => fn(exec));
      queue = next.catch(() => {});
      return next;
    },
    query: (sql, params) => {
      const next = queue.then(() => exec(sql, params));
      queue = next.catch(() => {});
      return next;
    },
    close: () => db.close(),
  };
}

// ---------- Tradução de parâmetros ----------

const isPlainObject = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const cache = new Map();

// Converte ? e @nome para $1, $2... (ignorando o que está entre aspas simples)
function compile(sql) {
  let hit = cache.get(sql);
  if (hit) return hit;
  let out = '';
  let n = 0;
  const names = [];
  const index = {};
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'") {
      const end = sql.indexOf("'", i + 1);
      const stop = end === -1 ? sql.length : end + 1;
      out += sql.slice(i, stop);
      i = stop - 1;
    } else if (c === '?') {
      out += `$${++n}`;
      names.push(null);
    } else if (c === '@' && /[A-Za-z_]/.test(sql[i + 1] || '')) {
      let j = i + 1;
      while (j < sql.length && /\w/.test(sql[j])) j++;
      const name = sql.slice(i + 1, j);
      if (!(name in index)) { index[name] = ++n; names.push(name); }
      out += `$${index[name]}`;
      i = j - 1;
    } else {
      out += c;
    }
  }
  hit = { text: out, names };
  cache.set(sql, hit);
  return hit;
}

function bindValue(v) {
  if (v === undefined) return null;
  if (typeof v === 'boolean') return v ? 1 : 0;
  return v;
}

function bind(names, args) {
  if (args.length === 1 && isPlainObject(args[0])) {
    const obj = args[0];
    return names.map((name) => bindValue(obj[name]));
  }
  const flat = args.length === 1 && Array.isArray(args[0]) ? args[0] : args;
  return flat.map(bindValue);
}

// ---------- Conexão e transações ----------

let driver = null;
let migrated = null;
const als = new AsyncLocalStorage();

function exec(sql, params) {
  const store = als.getStore();
  return store ? store.query(sql, params) : driver.query(sql, params);
}

class Statement {
  constructor(sql) { this.sql = sql; }

  async all(...args) {
    const { text, names } = compile(this.sql);
    return (await exec(text, bind(names, args))).rows;
  }

  async get(...args) {
    return (await this.all(...args))[0];
  }

  async run(...args) {
    let { text, names } = compile(this.sql);
    const insert = /^\s*INSERT\b/i.test(text) && !/\bRETURNING\b/i.test(text);
    if (insert) text += ' RETURNING *';
    const r = await exec(text, bind(names, args));
    return { changes: r.rowCount, lastInsertRowid: insert && r.rows[0] ? r.rows[0].id : undefined };
  }
}

let savepoints = 0;
const facade = {
  prepare: (sql) => new Statement(sql),
  exec: (sql) => exec(sql),
  // Devolve uma função que roda fn numa transação (ou num savepoint, se já estiver em uma)
  transaction: (fn) => async (...args) => {
    if (als.getStore()) {
      const sp = `sp${++savepoints}`;
      await exec(`SAVEPOINT ${sp}`);
      try {
        const out = await fn(...args);
        await exec(`RELEASE SAVEPOINT ${sp}`);
        return out;
      } catch (err) {
        await exec(`ROLLBACK TO SAVEPOINT ${sp}`);
        throw err;
      }
    }
    return request(() => fn(...args));
  },
};

// Roda fn numa transação com a trava global. Todas as consultas feitas dentro de fn usam essa transação.
async function request(fn) {
  if (!driver) throw new Error('Banco de dados não inicializado');
  if (als.getStore()) return fn();
  if (!migrated) migrated = migrate().catch((err) => { migrated = null; throw err; });
  await migrated;
  return driver.session(async (query) => {
    await query('BEGIN');
    try {
      await query('SELECT pg_advisory_xact_lock($1)', [LOCK_ID]);
      const out = await als.run({ query }, fn);
      await query('COMMIT');
      return out;
    } catch (err) {
      await query('ROLLBACK').catch(() => {});
      throw err;
    }
  });
}

async function migrate() {
  return driver.session(async (query) => {
    await query('BEGIN');
    try {
      await query('SELECT pg_advisory_xact_lock($1)', [LOCK_ID]);
      await query('CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)');
      const row = (await query('SELECT version FROM schema_version')).rows[0];
      const current = row ? row.version : 0;
      for (let v = current; v < MIGRATIONS.length; v++) await query(MIGRATIONS[v]);
      if (current < MIGRATIONS.length) {
        await query(RLS_SQL);
        if (row) await query('UPDATE schema_version SET version = $1', [MIGRATIONS.length]);
        else await query('INSERT INTO schema_version (version) VALUES ($1)', [MIGRATIONS.length]);
      }
      await query('COMMIT');
    } catch (err) {
      await query('ROLLBACK').catch(() => {});
      throw err;
    }
  });
}

// Abre a conexão. Sem DATABASE_URL usa o PGlite em dataDir (ou na memória, se dataDir = null).
function open({ url = process.env.DATABASE_URL, dataDir } = {}) {
  if (driver) return facade;
  driver = url ? pgDriver(url) : pgliteDriver(dataDir === undefined ? path.join(__dirname, '..', '.data', 'pglite') : dataDir);
  return facade;
}

async function close() {
  if (driver) await driver.close();
  driver = null;
  migrated = null;
}

function get() {
  if (!driver) throw new Error('Banco de dados não inicializado');
  return facade;
}

module.exports = { open, close, get, request, migrate, TABLES, schemaVersion: MIGRATIONS.length };
